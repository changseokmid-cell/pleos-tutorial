"""ADB/mock-input edge trials. This is not a natural Gleo or human voice test."""
import emulator_test as t
import json,time
t.OUT=t.ROOT/'evidence'/'exception-trial';t.OUT.mkdir(parents=True,exist_ok=True)
def gleo(action,params):
    t.shell('am','broadcast','--user','current','-n','kr.pleosguide/.GleoReceiver','-a',action,'--es','ACTION_PARAM',json.dumps(params,ensure_ascii=False))
try:
    t.record('PROVENANCE',input='MOCK_EVENT and ADB UNVERIFIED_INTENT; no actual human recognition')
    t.test(command='STOP');time.sleep(2)
    t.shell('am','start','--user','current','-n','kr.pleosguide/.MainActivity');time.sleep(2)
    t.console('gear',gear='Park');t.console('seat',kind='occupied',area='passenger',value='true')
    t.console('hvac',power='true',dual='true',driver_temp=21,passenger_temp=21)
    mark=len(t.logs());gleo('SET_TUTORIAL_MODE',{'enabled':True});t.wait('MODE_ON',start=mark)
    t.wait('SNAPSHOT','driverTemp, value=21.0',start=mark)
    mark=len(t.logs());t.console('seat',kind='occupied',area='passenger',value='false')
    t.wait('SNAPSHOT','passengerOccupied, value=false',start=mark)
    mark=len(t.logs());t.test(feature='SYNC');time.sleep(3)
    assert not any(e['kind']=='OFFER' for e in t.logs()[mark:])
    t.record('PASS',check='Empty passenger seat blocks SYNC')
    t.console('seat',kind='occupied',area='passenger',value='true');time.sleep(3)
    mark=len(t.logs());gleo('START_FEATURE_GUIDE',{'feature':'ERGO'});offer=t.wait('OFFER',start=mark)
    t.wait('GLEO_CALLBACK_SENT','"status":"success"',start=mark)
    sid=offer['sessionId'];mark=len(t.logs());gleo('START_FEATURE_GUIDE',{'feature':'SOUND'})
    t.wait('DUPLICATE_SUPPRESSED',start=mark)
    t.wait('GLEO_CALLBACK_SENT','"status":"fail"',start=mark)
    mark=len(t.logs());gleo('RESPOND_TO_GUIDE',{'sessionId':sid,'response':'네'})
    t.wait('CONSENT',start=mark);t.wait('GLEO_CALLBACK_SENT','"status":"success"',start=mark)
    mark=len(t.logs());t.console('gear',gear='Drive')
    t.wait('SESSION_END','주행 중',start=mark)
    t.record('PASS',check='Active guide ends on live Drive/UX restriction; no vehicle writes')
    t.console('gear',gear='Park');time.sleep(3)
    mark=len(t.logs());t.test(feature='ERGO');t.wait('OFFER',start=mark)
    t.test(text='싫어요');t.wait('SESSION_END','취소',start=mark)
    t.record('PASS',check='Explicit rejection ends session')
    mark=len(t.logs());t.test(feature='ERGO');t.wait('OFFER',start=mark)
    t.shell('input','keyevent','KEYCODE_HOME')
    t.wait('SESSION_END','무응답',start=mark,timeout=110)
    t.record('PASS',check='90-second no-response expiry while main Activity is backgrounded')
    mark=len(t.logs());t.console('hvac',passenger_temp=22)
    t.wait('SNAPSHOT','passengerTemp, value=22.0',start=mark)
    t.record('PASS',check='Foreground service still receives SDK changes after Home')
    t.test(command='YIELD');time.sleep(1);t.test(command='STOP');time.sleep(2)
finally:
    all_entries=t.logs()
    (t.OUT/'all-debug-history.jsonl').write_text('\n'.join(json.dumps(e,ensure_ascii=False) for e in all_entries)+'\n',encoding='utf8')
    t.record('PRESERVED_DEBUG_HISTORY',events=len(all_entries),tts_done=sum(e['kind']=='TTS_DONE' for e in all_entries))
